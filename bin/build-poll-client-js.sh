#!/usr/bin/env bash
# Regenerate the embedded copy of the meeting-poll invitee page's client
# module. poll.client.js stays the single source of truth; this only wraps
# it as a TS string module so the worker can import it without a Text rule.
# Same pattern as bin/build-client-js.sh for the booking page.
#
# Uses JSON.stringify rather than a String.raw template literal: the source
# contains real backtick/${...} template literals in executable code (e.g. the
# "Unknown timezone" error message), not just comments, and String.raw's raw
# value keeps escaping backslashes literally — a sed-escaped String.raw
# template would ship broken JS to the browser. JSON.stringify round-trips
# the source exactly, whatever characters it contains.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=worker/src/polls/poll.client.js
OUT=worker/src/polls/poll-client-source.generated.ts
node -e '
const fs = require("fs");
const crypto = require("crypto");
const [, src, out] = process.argv;
const text = fs.readFileSync(src, "utf8");
// Content hash, embedded in the served filename so the asset can be cached
// immutably. Any edit to poll.client.js changes the URL, so a deploy
// reaches browsers immediately instead of waiting out a max-age. 16 hex
// chars (64 bits) is far beyond collision risk for one file with one author.
const hash = crypto.createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16);
const header = "// GENERATED by bin/build-poll-client-js.sh — do not edit. Source: poll.client.js\n";
fs.writeFileSync(
  out,
  header +
    "export const POLL_CLIENT_JS = " + JSON.stringify(text) + ";\n" +
    "export const POLL_CLIENT_HASH = " + JSON.stringify(hash) + ";\n",
);
console.log("  hash " + hash);
' "$SRC" "$OUT"
echo "wrote $OUT"
